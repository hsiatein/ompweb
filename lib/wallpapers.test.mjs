test("wallpaper preferences are bounded and reject invalid identifiers", () => {
  assert.equal(parseWallpaperPreferences("broken").id, null);
  assert.equal(parseWallpaperPreferences('{"id":"../../secret","brightness":500,"glass":"weird"}').brightness, 100);
  assert.equal(parseWallpaperPreferences('{"id":"../../secret"}').id, null);
  assert.equal(parseWallpaperPreferences('{"glass":"clear"}').glass, "clear");
  assert.equal(parseWallpaperPreferences(null).glassOpacity, 35);
  assert.equal(parseWallpaperPreferences(null).adaptiveText, true);
  assert.equal(parseWallpaperPreferences(null).textMode, "material");
  assert.equal(parseWallpaperPreferences('{"textMode":"auto"}').textMode, "auto");
  assert.equal(parseWallpaperPreferences('{"textMode":"fixed","textColor":"#ABCDEF"}').textColor, "#abcdef");
  assert.equal(parseWallpaperPreferences('{"textMode":"fixed"}').textMode, "fixed");
  assert.equal(parseWallpaperPreferences('{"textMode":"unknown","textColor":"red"}').textMode, "material");
  assert.equal(parseWallpaperPreferences('{"textColor":"url(secret)"}').textColor, "#e4e6ed");
  assert.equal(parseWallpaperPreferences('{"adaptiveText":false}').adaptiveText, false);
  assert.equal(parseWallpaperPreferences('{"adaptiveText":"false"}').adaptiveText, true);
  assert.equal(parseWallpaperPreferences(null).adaptivePalette, false);
  assert.equal(parseWallpaperPreferences('{"adaptivePalette":true}').adaptivePalette, true);
  assert.equal(parseWallpaperPreferences('{"adaptivePalette":"true"}').adaptivePalette, false);
  assert.equal(parseWallpaperPreferences('{"brightness":75}').glassOpacity, 35);
  assert.equal(parseWallpaperPreferences('{"glassOpacity":18}').glassOpacity, 18);
  assert.equal(parseWallpaperPreferences('{"glassOpacity":-5}').glassOpacity, 0);
  assert.equal(parseWallpaperPreferences('{"glassOpacity":150}').glassOpacity, 100);
  assert.equal(parseWallpaperPreferences('{"glassOpacity":"20"}').glassOpacity, 35);
  assert.equal(parseWallpaperPreferences('{"kind":"scene"}').kind, "scene");
});
test("video ranges handle open, suffix, invalid and multiple ranges", () => {
  assert.equal(store.mediaRange(null, 100), null);
  assert.deepEqual(store.mediaRange("bytes=10-19", 100), { start: 10, end: 19 });
  assert.deepEqual(store.mediaRange("bytes=10-", 100), { start: 10, end: 99 });
  assert.deepEqual(store.mediaRange("bytes=-20", 100), { start: 80, end: 99 });
  assert.deepEqual(store.mediaRange("bytes=90-200", 100), { start: 90, end: 99 });
  for (const r of ["bytes=100-", "bytes=20-10", "bytes=-0", "bytes=-", "bytes=1-2,3-4", "junk"]) assert.throws(() => store.mediaRange(r, 100));
});
