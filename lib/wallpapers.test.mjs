test("library imports stream, reject spoofed content, keep WE scenes distinct and never delete originals", async t => {
  const root = await fs.mkdtemp(path.join(tmpdir(), "omp-wallpaper-test-"));
  const old = process.env.PI_CODING_AGENT_DIR;
  const oldRoots = process.env.OMP_WEB_WALLPAPER_DIRS;
  process.env.PI_CODING_AGENT_DIR = path.join(root, "agent");
  process.env.OMP_WEB_WALLPAPER_DIRS = "";
  store.invalidateWallpapers();
  t.after(async () => {
    if (old === undefined) delete process.env.PI_CODING_AGENT_DIR; else process.env.PI_CODING_AGENT_DIR = old;
    if (oldRoots === undefined) delete process.env.OMP_WEB_WALLPAPER_DIRS; else process.env.OMP_WEB_WALLPAPER_DIRS = oldRoots;
    store.invalidateWallpapers();
    const resolved = await fs.realpath(root);
    assert.ok(resolved.startsWith(await fs.realpath(tmpdir())) && path.basename(resolved).startsWith("omp-wallpaper-test-"));
    await fs.rm(resolved, { recursive: true, force: true });
  });
  const imported = await store.importWallpaper(new Request("http://localhost/upload", { method: "POST", body: png }), "test.png");
  let list = await store.listWallpapers(true);
  assert.equal(list.wallpapers.length, 1);
  const media = await store.resolveWallpaperMedia(imported.id, false);
  assert.deepEqual(await media.handle.readFile(), png);
  await media.handle.close();
  await assert.rejects(store.importWallpaper(new Request("http://localhost/upload", { method: "POST", body: "<html>bad</html>" }), "fake.png"));
  await assert.rejects(store.importWallpaper(new Request("http://localhost/upload", { method: "POST", body: png, headers: { "content-length": String(store.MAX_WALLPAPER_BYTES + 1) } }), "large.png"));
  await assert.rejects(store.importWallpaper(new Request("http://localhost/upload", { method: "POST", body: png }), ".hidden.png"));
  const originals = path.join(root, "originals");
  const scene = path.join(originals, "scene");
  await fs.mkdir(scene, { recursive: true });
  await fs.writeFile(path.join(scene, "preview.png"), png);
  await fs.writeFile(path.join(scene, "project.json"), JSON.stringify({ type: "scene", file: "scene.json", preview: "preview.png", title: "Real scene" }));
  await fs.writeFile(path.join(originals, "image.png"), png);
  await store.addWallpaperRoot(originals);
  list = await store.listWallpapers(true);
  assert.equal(list.wallpapers.length, 3);
  const item = list.wallpapers.find(w => w.kind === "scene");
  assert.ok(item.preview);
  await assert.rejects(store.resolveWallpaperMedia(item.id, false));
  await assert.rejects(store.resolveSceneProject("../private"));
  await assert.rejects(store.resolveSceneProject(item.id));
  await fs.writeFile(path.join(scene, "scene.pkg"), "scene fixture");
  const sceneProject = await store.resolveSceneProject(item.id);
  assert.equal(sceneProject.project, path.join(scene, "project.json"));
  await assert.rejects(store.resolveSceneProject(imported.id));
  const preview = await store.resolveWallpaperMedia(item.id, true);
  await preview.handle.close();
  await assert.rejects(store.deleteWallpaper(item.id));
  await assert.rejects(store.safeWallpaperFile(scene, "../image.png"));
  await assert.rejects(store.safeWallpaperFile(scene, "/etc/passwd"));
  await assert.rejects(store.safeWallpaperFile(scene, "..\\image.png"));
  const link = path.join(scene, "escape");
  await fs.symlink(originals, link, "junction");
  await assert.rejects(store.safeWallpaperFile(scene, "escape/image.png"));
  await fs.rmdir(link);
  await store.deleteWallpaper(imported.id);
  assert.equal((await store.listWallpapers(true)).wallpapers.length, 2);
  assert.deepEqual(await fs.readFile(path.join(originals, "image.png")), png);
});
